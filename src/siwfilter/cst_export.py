"""Generate a CST Studio Suite 2021 VBA macro (`siw_filter.bas`) building the
SIW bandpass filter as NATIVE parametric 3D solids.

Every scalar dimension is stored with StoreParameter so it can be re-tuned in
the CST GUI; every geometry block is wrapped in AddToHistory so the solids
survive a History rebuild. Via positions are computed here (Python) and
emitted as explicit Cylinder blocks (parametric in radius/height).

Usage by the human with CST 2021:
    CST -> Home -> Macros -> Open VBA Macro Editor -> File > Open siw_filter.bas -> F5
(or Macros > Run on the file). No live link needed.

Run:  uv run python cst_export.py
"""

from __future__ import annotations

from .config import SPEC, FilterSpec, out_bas
from .siw_geometry import Geometry, build_geometry

MM = 1e3  # metres -> mm (CST units set to mm)


def _f(x: float) -> str:
    """Format a length in METRES (anything read off `Geometry`) as mm."""
    return f"{x * MM:.4f}"


def _fmm(x: float) -> str:
    """Format a length ALREADY in mm (launch dict fields, gnd_stitch_layout
    output). Do not mix these two -- feeding metres here or mm to `_f`
    silently scales by 1000 with no error."""
    return f"{x:.4f}"


def _hist(header: str, body_lines: list[str]) -> str:
    """Wrap a VBA command block in AddToHistory (CST history-rebuild safe)."""
    body = '" & vbLf & _\n  "'.join(line.replace('"', '""') for line in body_lines)
    return f'AddToHistory "{header}", "{body}"\n'


def generate_bas(g: Geometry, launch: dict | None = None,
                 sma_len_mm: float = 6.0,
                 flat_sma_ground: bool = False) -> str:
    """VBA macro for CST. `launch` is a TAOGLAS_CPWG-style dict; when given,
    the feed is built as the REAL launch actually simulated -- coplanar
    ground pours, stitching vias, the narrowed CPWG feed with its taper out
    to the microstrip, and the Taoglas SMA coax stub with coaxial ports --
    instead of a bare constant-width microstrip with waveguide ports.

    flat_sma_ground defaults back to False (2026-09-06, reverted same day
    it was added): it matches Palace's ground-clip geometry more closely,
    but a real CST run with it on came back with "the calculation seems
    to be unstable" and S-parameters that violate passivity everywhere in
    the sweep (S11 never negative across 1001 points, up to +39). The clip
    cuts the 0.3mm PEC shield with a Boolean Subtract right at the board
    edge, producing a sharp full-round -> D-shaped cross-section step --
    a classic PBA thin/degenerate-cell trigger with no counterpart in
    Palace's tet mesh. Not proven beyond doubt (no CST license here to
    A/B test), but it is the one geometry change coincident with both the
    instability warning and the visibly stepped connector the fab contact
    flagged, and the tangent-line ground contact it "fixed" never
    corresponded to an observed failure the way the other 4 fixes did.
    Kept as an explicit opt-in for whoever revisits this with a real CST
    session to test. Palace's own build_mesh() unconditionally clips the
    PTFE/shield near the board edge to z>=0 there (the `clipbox` cut,
    palace_driven.py ~line 234) so the shield sits flush on the bottom
    ground plane -- there is no "unclipped" mode in what Palace
    actually simulates. Pass True explicitly to re-enable it."""
    if sma_len_mm <= 0:
        raise ValueError("SMA length must be positive")
    has_cpwg = bool(launch and launch.get("cpwg_gap_mm") is not None)
    if flat_sma_ground and not has_cpwg:
        raise ValueError("flat_sma_ground requires a CPWG/SMA launch")
    spec, sub = g.spec, g.spec.substrate
    half = g.a_siw / 2.0
    L_inner = g.L_inner
    Lt, Lf, W = g.L_taper, g.L_feed, g.W_ms
    xmin, xmax = -Lt - Lf, L_inner + Lt + Lf          # board ends at the feeds
    _, _, ymin, ymax = g.board
    # Parametric X expressions so W_ms/L_taper/L_feed are LIVE knobs in CST:
    # the board edges and ports track the feed length. L_inner stays numeric
    # (locked to the baked via walls) so changing feed dims never desyncs them.
    Li = _f(L_inner)
    xmin_e = "-(L_taper+L_feed)"
    xmax_e = f"{Li}+L_taper+L_feed"
    t_cu = sub.cu_thickness
    h_air = 6.0 * sub.h                                # air above the board

    s = []
    s.append(f'''\
' =====================================================================
'  SIW bandpass filter — auto-generated by cst_export.py
'  f0 = {spec.f0/1e9:.3f} GHz, N = {spec.N}, FBW = {spec.FBW*100:.1f} %, ripple = {spec.ripple_db} dB
'  substrate: {sub.name} (eps_r = {sub.eps_r}, tan_d = {sub.tan_d}, h = {sub.h*MM:.3f} mm)
'  irises: {"geometry supplied by project; verify provenance in the package" if g.iris_calibrated else "ANALYTICAL PLACEHOLDER — not an EM-validated design"}
'  Audit revision: 2026-09-06-R6; connector ground: {'flat (matches Palace)' if flat_sma_ground else 'unclipped edge contact'}.
'  CST execution NOT validated locally; compare magnitude with both Palace meshes.
'  CST Studio Suite 2021 — open in VBA macro editor and press F5.
' =====================================================================
Option Explicit

Sub Main

ResetAll

' ---- units & frequency range -------------------------------------
AddToHistory "define units", "With Units" & vbLf & _
  ".Geometry ""mm""" & vbLf & ".Frequency ""GHz""" & vbLf & _
  ".Time ""ns""" & vbLf & "End With"
AddToHistory "define frequency range", "Solver.FrequencyRange ""2.0"", ""3.6"""
''')

    # ---- parameters ----------------------------------------------------
    params = [
        ("eps_r",  f"{sub.eps_r}",      "substrate Dk"),
        ("tan_d",  f"{sub.tan_d}",      "substrate Df"),
        ("h_sub",  _f(sub.h),           "substrate thickness [mm]"),
        ("t_cu",   _f(t_cu),            "copper thickness [mm]"),
        ("rvia",   _f(spec.d_via / 2),  "via radius [mm]"),
        ("p_via",  _f(spec.p_via),      "via pitch [mm]; main-fence centres are fixed"),
        ("a_siw",  _f(g.a_siw),         "SIW width [mm]; reference only, main fence is fixed"),
        ("L_taper", _f(Lt),             "ms->SIW taper length [mm]"),
        ("L_feed", _f(Lf),              "50-ohm feed length [mm]"),
        ("W_ms",   _f(W),               "50-ohm microstrip width [mm]"),
        ("Lsub",   _f(xmax - xmin),     "board length [mm]"),
        ("Wsub",   _f(ymax - ymin),     "board width [mm]"),
        ("h_air",  _f(h_air),           "air above board [mm]"),
    ]
    # One L_cav per cavity -- they generally differ, and a single "L_cav"
    # StoreParameter would mislabel every cavity but one.
    for i, Lc in enumerate(g.L_cavs, start=1):
        params.append((f"L_cav{i}", _f(Lc), f"cavity {i} length [mm] "
                                            f"(read-only: vias are baked)"))
    for i, w in enumerate(g.iris_widths, start=1):
        params.append((f"w_iris{i}{i+1}", _f(w), f"iris {i}-{i+1} width [mm]; reference only, centres are fixed"))
    # External coupling aperture (input/output iris) -> controls Qe -> bandwidth.
    # Use the geometry's w_ext (Palace-optimized when USE_OPTIMIZED) so the GUI
    # parameter matches the baked via positions.
    params.append(("w_ext", _f(g.w_ext),
                   "EXTERNAL iris gap (input/output) -> Qe -> bandwidth [mm]"))

    s.append("\n' ---- parameters (some are reference-only; see comments) -----------\n")
    for name, val, desc in params:
        s.append(f'StoreParameter "{name}", "{val}"   \' {desc}\n')

    # ---- material -------------------------------------------------------
    mat = sub.name.replace(".", "p")
    s.append("\n' ---- substrate material ------------------------------------------\n")
    s.append(_hist(f"define material: {mat}", [
        "With Material", ".Reset", f'.Name "{mat}"', '.Folder ""',
        '.Type "Normal"', '.Epsilon "eps_r"', '.Mu "1"',
        '.TanD "tan_d"', '.TanDFreq "10"', '.TanDGiven "True"',
        '.TanDModel "ConstTanD"', '.DispModelEps "None"',
        '.Colour "0.75", "0.85", "0.6"', ".Create", "End With",
    ]))

    # ---- substrate + grounds -------------------------------------------
    def brick(name, material, xr, yr, zr):
        return _hist(f"define brick: component1:{name}", [
            "With Brick", ".Reset", f'.Name "{name}"',
            '.Component "component1"', f'.Material "{material}"',
            f'.Xrange "{xr[0]}", "{xr[1]}"',
            f'.Yrange "{yr[0]}", "{yr[1]}"',
            f'.Zrange "{zr[0]}", "{zr[1]}"',
            ".Create", "End With",
        ])

    s.append("\n' ---- substrate + ground planes ------------------------------------\n")
    s.append(brick("substrate", mat,
                   (xmin_e, xmax_e), (_f(ymin), _f(ymax)), ("0", "h_sub")))
    s.append(brick("gnd_bottom", "PEC",
                   (xmin_e, xmax_e), (_f(ymin), _f(ymax)), ("-t_cu", "0")))
    # Top SIW plate covers the cavity section only (tapers/feeds are traces).
    s.append(brick("siw_top", "PEC",
                   ("0", Li), (_f(ymin), _f(ymax)),
                   ("h_sub", "h_sub+t_cu")))

    # ---- vias -----------------------------------------------------------
    s.append("\n' ---- vias (PEC cylinders through the substrate) -------------------\n")
    for i, (x, y) in enumerate(g.vias):
        s.append(_hist(f"define cylinder: component1:via{i:03d}", [
            "With Cylinder", ".Reset", f'.Name "via{i:03d}"',
            '.Component "component1"', '.Material "PEC"',
            '.Axis "z"', '.Outerradius "rvia"', '.Innerradius "0"',
            f'.Xcenter "{_f(x)}"', f'.Ycenter "{_f(y)}"',
            '.Zrange "0", "h_sub+t_cu"', '.Segments "0"',
            ".Create", "End With",
        ]))

    # ---- external coupling irises (input/output) -----------------------
    # Transverse via rows at the SIW input/output faces with a central gap of
    # w_ext. Narrowing w_ext weakens the external coupling (raises Qe), which
    # narrows the bandwidth. The Y positions reference the w_ext parameter so
    # the gap is tunable directly in CST.
    s.append("\n' ---- external coupling irises (gap = w_ext, controls Qe/BW) -------\n")
    # vias per face = total ext iris vias / (2 faces * 2 signs); matches
    # siw_geometry so the .bas never places a via past the side wall.
    n_ext = len(g.ext_iris_vias) // 4
    faces = {"in": "0", "out": _f(L_inner)}
    for fname, xexpr in faces.items():
        for k in range(n_ext):
            off = f"w_ext/2 + {k + 0.5:.1f}*p_via"
            for sgn, tag in (("+", "t"), ("-", "b")):
                yc = f"{off}" if sgn == "+" else f"-({off})"
                s.append(_hist(f"define cylinder: component1:viaext_{fname}_{tag}{k}", [
                    "With Cylinder", ".Reset",
                    f'.Name "viaext_{fname}_{tag}{k}"',
                    '.Component "component1"', '.Material "PEC"',
                    '.Axis "z"', '.Outerradius "rvia"', '.Innerradius "0"',
                    f'.Xcenter "{xexpr}"', f'.Ycenter "{yc}"',
                    '.Zrange "0", "h_sub+t_cu"', '.Segments "0"',
                    ".Create", "End With",
                ]))

    # ---- tapers + feed traces (extruded point-list polygons) -----------
    s.append("\n' ---- microstrip feeds + tapers (extruded copper traces) -----------\n")
    # Coordinates are VBA expressions referencing the feed parameters W_ms,
    # L_taper, L_feed (LIVE in CST). The taper opens to +/-a_siw/2 (numeric,
    # locked to the via walls). hp = half-width string, ht = a_siw/2 numeric.
    hp = "W_ms/2"
    ht = _f(half)
    # These point lists are a HAND-DUPLICATION of
    # palace_dualmode_driven.feed_trace_poly's geometry, not a call to it --
    # unavoidable here since CST needs the live VBA parameter names
    # (L_taper/L_feed/W_ms) in these coordinate slots, and feed_trace_poly
    # only accepts numeric floats. Verified against a numeric call to
    # feed_trace_poly with this design's actual values (2026-09-06,
    # adversarial re-review): exact vertex-for-vertex match, 10/10 points.
    # That match is NOT guaranteed to survive a future edit to
    # feed_trace_poly -- if its geometry ever changes, re-run that same
    # numeric comparison before trusting this file again.
    traces = {
        "taper_in": [("-L_taper", hp), ("0", ht), ("0", f"-({ht})"),
                     ("-L_taper", f"-({hp})")],
        "feed_in": [("-(L_taper+L_feed)", hp), ("-L_taper", hp),
                    ("-L_taper", f"-({hp})"), ("-(L_taper+L_feed)", f"-({hp})")],
        "taper_out": [(f"{Li}+L_taper", hp), (Li, ht), (Li, f"-({ht})"),
                      (f"{Li}+L_taper", f"-({hp})")],
        "feed_out": [(f"{Li}+L_taper+L_feed", hp), (f"{Li}+L_taper", hp),
                     (f"{Li}+L_taper", f"-({hp})"),
                     (f"{Li}+L_taper+L_feed", f"-({hp})")],
    }
    if launch and launch.get("cpwg_gap_mm") is not None:
        # Real CPWG launch: feed narrows to cpwg_w_feed_mm at the board edge
        # and tapers out to the microstrip width where the pours end. The two
        # 50-ohm widths differ (a CPWG's impedance is set by its gap), so a
        # constant-width feed here would NOT be the simulated structure.
        wp = launch["cpwg_w_feed_mm"]; hp2 = _fmm(wp / 2.0)
        clen = launch.get("cpwg_len_mm", 5.0); ctap = launch.get("cpwg_taper_mm", 4.0)
        # Overwrite feed_in/feed_out only -- taper_in/taper_out (the SIW-facing
        # flare from the microstrip width out to the full cavity width, added
        # above) are unrelated to the launch and must survive this branch.
        # Reassigning the whole dict here once left them out entirely: the
        # copper ended at the microstrip width (x=-L_taper) with nothing
        # connecting it to the cavity's top plate at x=0 -- an ~L_taper-long
        # (15.7mm) open gap in the trace, not merely a missing picture.
        traces["feed_in"] = [(xmin_e, hp2),
                             (f"{xmin_e}+{_fmm(clen)}", hp2),
                             (f"{xmin_e}+{_fmm(clen + ctap)}", hp),
                             ("-L_taper", hp), ("-L_taper", f"-({hp})"),
                             (f"{xmin_e}+{_fmm(clen + ctap)}", f"-({hp})"),
                             (f"{xmin_e}+{_fmm(clen)}", f"-({hp2})"),
                             (xmin_e, f"-({hp2})")]
        traces["feed_out"] = [(xmax_e, hp2),
                              (f"{xmax_e}-{_fmm(clen)}", hp2),
                              (f"{xmax_e}-{_fmm(clen + ctap)}", hp),
                              (f"{Li}+L_taper", hp), (f"{Li}+L_taper", f"-({hp})"),
                              (f"{xmax_e}-{_fmm(clen + ctap)}", f"-({hp})"),
                              (f"{xmax_e}-{_fmm(clen)}", f"-({hp2})"),
                              (xmax_e, f"-({hp2})")]
        y_g, y_o = launch["cpwg_y_gnd_mm"], launch["cpwg_y_out_mm"]
        for side, sgn in (("top", 1.0), ("bot", -1.0)):
            for end, xa, xb in (("in", xmin_e, f"{xmin_e}+{_fmm(clen)}"),
                                ("out", f"{xmax_e}-{_fmm(clen)}", xmax_e)):
                traces[f"cpwg_gnd_{end}_{side}"] = [
                    (xa, _fmm(sgn * y_g)), (xb, _fmm(sgn * y_g)),
                    (xb, _fmm(sgn * y_o)), (xa, _fmm(sgn * y_o))]
    for name, pts in traces.items():
        body = ["With Extrude", ".Reset", f'.Name "{name}"',
                '.Component "component1"', '.Material "PEC"',
                '.Mode "pointlist"', '.Height "t_cu"',
                '.Twist "0"', '.Taper "0"',
                '.Origin "0", "0", "h_sub"',
                '.Uvector "1", "0", "0"', '.Vvector "0", "1", "0"',
                f'.Point "{pts[0][0]}", "{pts[0][1]}"']
        for (x, y) in pts[1:]:
            body.append(f'.LineTo "{x}", "{y}"')
        body += [".Create", "End With"]
        s.append(_hist(f"define extrude: component1:{name}", body))

    # ---- CPWG stitching vias + the real Taoglas SMA ---------------------
    if launch and launch.get("cpwg_gap_mm") is not None:
        from .palace_dualmode_driven import gnd_stitch_layout
        # gnd_stitch_layout works in MILLIMETRES; Geometry stores METRES.
        # Passing metres silently returns an empty via list, not an error.
        _mm = 1e3
        ym_l = ymax * _mm
        _, gnd_vias = gnd_stitch_layout(
            -(Lt + Lf) * _mm, (L_inner + Lt + Lf) * _mm, W * _mm, ym_l, -ym_l,
            n_gnd_stitch=launch.get("n_gnd_stitch", 6),
            gnd_stitch_offset_mm=launch.get("gnd_stitch_offset_mm", 2.62),
            gnd_stitch_pitch_mm=launch.get("gnd_stitch_pitch_mm", 1.2),
            gnd_via_d_mm=launch.get("gnd_via_d_mm", 0.6),
            gnd_clearance_mm=launch.get("gnd_clearance_mm", 0.3),
            cpwg_gap_mm=launch.get("cpwg_gap_mm"),
            cpwg_y_gnd_mm=launch.get("cpwg_y_gnd_mm"),
            cpwg_y_out_mm=launch.get("cpwg_y_out_mm"),
            cpwg_len_mm=launch.get("cpwg_len_mm", 5.0),
            cpwg_taper_mm=launch.get("cpwg_taper_mm", 4.0))
        rg = launch.get("gnd_via_d_mm", 0.6) / 2.0
        s.append("\n' ---- CPWG ground stitching vias ---------------------------------\n")
        s.append(f"' {len(gnd_vias)} stitching vias (MEASURED from the shared\n"
                 f"' gnd_stitch_layout, the same helper the EM mesh uses)\n")
        for i, (vx, vy) in enumerate(gnd_vias):
            s.append(_hist(f"define cylinder: component1:gndvia{i:03d}", [
                "With Cylinder", ".Reset", f'.Name "gndvia{i:03d}"',
                '.Component "component1"', '.Material "PEC"',
                '.Axis "z"', f'.Outerradius "{_fmm(rg)}"', '.Innerradius "0"',
                f'.Xcenter "{_fmm(vx)}"', f'.Ycenter "{_fmm(vy)}"',
                '.Zrange "-t_cu", "h_sub+t_cu"', '.Segments "0"',
                ".Create", "End With"]))

        # Simplified Taoglas-sized coax, not a full manufacturer connector CAD.
        # Palace centres the pin at z=h_sub and unconditionally clips the
        # near-board PTFE/shield to z>=0 over ~1.6mm (nominal 1.5mm plus
        # Boolean tolerance) so the shield sits flush on the bottom ground
        # plane -- there is no unclipped mode in what Palace simulates.
        # flat_sma_ground now defaults to matching that (see generate_bas'
        # docstring) whenever a real CPWG/SMA launch is present.
        rin, rout = launch["sma_rin_mm"], launch["sma_rout_mm"]
        shell_t = 0.3   # excluded PEC shell volume; its outer geometry can
                        # affect fringe fields even though it has no loss.
        s.append("\n' ---- Taoglas SMA coax stubs (real connector) --------------------\n")
        s.append(_hist("define material: PTFE_sma", [
            "With Material", ".Reset", '.Name "PTFE_sma"', '.Folder ""',
            '.Type "Normal"', f'.Epsilon "{launch["sma_eps_r"]}"', '.Mu "1"',
            f'.TanD "{launch["sma_tand"]}"', '.TanDGiven "True"',
            '.TanDModel "ConstTanD"', '.Colour "0.9", "0.9", "0.9"',
            ".Create", "End With"]))
        for tag, x_edge, sgn in (("in", xmin_e, -1.0), ("out", xmax_e, 1.0)):
            far = f"{x_edge}{'-' if sgn < 0 else '+'}{_fmm(sma_len_mm)}"
            xr = (far, x_edge) if sgn < 0 else (x_edge, far)
            s.append(_hist(f"define cylinder: component1:sma_{tag}_ptfe", [
                "With Cylinder", ".Reset", f'.Name "sma_{tag}_ptfe"',
                '.Component "component1"', '.Material "PTFE_sma"',
                '.Axis "x"', f'.Outerradius "{_fmm(rout)}"',
                f'.Innerradius "{_fmm(rin)}"',
                f'.Xrange "{xr[0]}", "{xr[1]}"',
                '.Ycenter "0"', '.Zcenter "h_sub"', '.Segments "0"',
                ".Create", "End With"]))
            s.append(_hist(f"define cylinder: component1:sma_{tag}_pin", [
                "With Cylinder", ".Reset", f'.Name "sma_{tag}_pin"',
                '.Component "component1"', '.Material "PEC"',
                '.Axis "x"', f'.Outerradius "{_fmm(rin)}"', '.Innerradius "0"',
                f'.Xrange "{xr[0]}", "{xr[1]}"',
                '.Ycenter "0"', '.Zcenter "h_sub"', '.Segments "0"',
                ".Create", "End With"]))
            # Shield: Palace has no separate solid for this -- its mesh tags
            # the PTFE's own outer face (r=rout) PEC directly, which is a
            # valid coax boundary in an FEM mesh but has no CST equivalent.
            # Without an actual PEC solid here the coax has no confining
            # wall along the stub and is not the structure that was
            # simulated. Innerradius = rout keeps it flush with the PTFE;
            # the port aperture below is sized to rout+shell_t (not rout)
            # so it fully encloses this conductor, not just touches its
            # inner face.
            s.append(_hist(f"define cylinder: component1:sma_{tag}_shield", [
                "With Cylinder", ".Reset", f'.Name "sma_{tag}_shield"',
                '.Component "component1"', '.Material "PEC"',
                '.Axis "x"', f'.Outerradius "{_fmm(rout + shell_t)}"',
                f'.Innerradius "{_fmm(rout)}"',
                f'.Xrange "{xr[0]}", "{xr[1]}"',
                '.Ycenter "0"', '.Zcenter "h_sub"', '.Segments "0"',
                ".Create", "End With"]))

            if flat_sma_ground:
                # Match Palace's flat z=0 ground contact without removing the
                # full circular coax port. Recreate the cutter because CST
                # Solid.Subtract consumes it. Keep the exposed vertical step
                # open, as in Palace; CST has air there, Palace an absorbing BC.
                clip_len = min(1.5, .4 * sma_len_mm) + .1
                near = f"{x_edge}{'-' if sgn < 0 else '+'}{_fmm(clip_len)}"
                clip_x = (near, x_edge) if sgn < 0 else (x_edge, near)
                ro = rout + shell_t
                if not rin < sub.h * MM < rout:
                    raise ValueError("Flat SMA variant requires rin < h_sub < rout")
                for part in ("ptfe", "shield"):
                    tool_name = f"sma_{tag}_{part}_clip"
                    s.append(brick(tool_name, "Vacuum", clip_x,
                                   (_fmm(-ro-1), _fmm(ro+1)),
                                   (_fmm(-ro-1), "0")))
                    s.append(_hist(f"clip SMA {tag} {part}", [
                        f'Solid.Subtract "component1:sma_{tag}_{part}", "component1:{tool_name}"']))

    # ---- boundaries, background, ports ----------------------------------
    s.append("\n' ---- background + boundaries --------------------------------------\n")
    s.append(_hist("define background", [
        "With Background", ".ResetBackground", '.Type "Normal"',
        '.XminSpace "0"', '.XmaxSpace "0"',
        # YminSpace/YmaxSpace were 0 from the very first version of this
        # file -- never touched by any of the X/Z boundary fixes -- so the
        # dispersive substrate (RO4350B, TanD-based loss) sat directly on
        # the open Y boundary with no air gap. A real CST run (2026-09-06)
        # flagged this explicitly: "Dispersive materials are not supported
        # at open boundary... Locations: ymin ymax". Palace's own mesh has
        # this same zero-Y-padding geometry (its own air boxes only cover
        # z>=h, not the Y sides), so this is not a Palace-mismatch fix --
        # it is a CST-specific requirement (its open/absorbing BC math
        # needs a non-dispersive buffer) that Palace's FEM formulation
        # apparently doesn't share. 2mm matches the standoff already used
        # for ZminSpace below, not a new arbitrary number.
        '.YminSpace "2.0"', '.YmaxSpace "2.0"',
        # ZminSpace is NOT 0: the real ground plane is the gnd_bottom PEC
        # solid, not this domain wall. With SMA stubs present (radius up to
        # ~1.56mm) as the lowest geometry in the model, ZminSpace=0 auto-
        # sizes the domain floor to sit TANGENT to the round connector shell
        # -- a cylinder only touches a flat plane along a line, so an
        # "electric" wall there would cover the whole board footprint as an
        # unphysical extra PEC sheet a hair below the connector, with no
        # counterpart in Palace's mesh (which has no z<0 volume at all;
        # everything the SMA stub's own geometry doesn't classify as its
        # own PEC surface -- see build_mesh's on_sma_shell/pin/cap -- is
        # absorbing). 2mm is a general absorbing-boundary standoff, not a
        # Palace parallel: Palace's own boundary IS the PTFE's r=rout face
        # directly there, with no buffer beyond it either.
        '.ZminSpace "2.0"', '.ZmaxSpace "h_air"',
        "End With",
    ]))
    s.append(_hist("define boundaries", [
        "With Boundary",
        # X was "electric" (PEC end-caps) until an adversarial re-review
        # (2026-09-06) caught it: XminSpace/XmaxSpace=0 fits the domain
        # tightly to the SMA stub ends, so an electric wall there shorts
        # the whole board-footprint cross-section outside the small coax
        # port disk with a PEC bulkhead. Palace has no counterpart -- its
        # classification loop (build_mesh, is_boundary catch-all) puts
        # every non-port, non-PEC face on the X extremes into `absorbing`,
        # same treatment as Y/Z. "open" matches that.
        '.Xmin "open"', '.Xmax "open"',
        '.Ymin "open"', '.Ymax "open"',
        '.Zmin "open"', '.Zmax "open"',
        '.ApplyInAllDirections "False"',
        "End With",
    ]))

    if launch and launch.get("cpwg_gap_mm") is not None:
        # COAXIAL ports on the outer face of each SMA stub. The EM model is
        # driven this way (wave ports on the coax cross-section), so
        # microstrip ports here would make the CST run a different problem
        # from the one the design was optimised against.
        #
        # The aperture is sized to rout+shell_t (the SHIELD's outer radius),
        # not rout (the dielectric/shield interface): a port window that
        # stops exactly at the enclosing conductor's inner face risks CST's
        # 2D port-mode solver not cleanly registering that PEC boundary.
        # This is inference, not a confirmed CST convention -- flagged as
        # unverified by adversarial re-review (2026-09-06), since this
        # environment has no CST install to check it against.
        rout = launch["sma_rout_mm"]
        shell_t = 0.3   # must match the shield Outerradius above
        rport = rout + shell_t
        s.append("\n' ---- coaxial ports on the SMA stubs -----------------------------\n")
        for n, (x_edge, sgn, orient) in enumerate(
                [(xmin_e, -1.0, "xmin"), (xmax_e, 1.0, "xmax")], start=1):
            face = f"{x_edge}{'-' if sgn < 0 else '+'}{_fmm(sma_len_mm)}"
            s.append(_hist(f"define port{n} (coax)", [
                "With Port", ".Reset", f'.PortNumber "{n}"',
                '.NumberOfModes "1"', '.Coordinates "Free"',
                f'.Orientation "{orient}"', '.PortOnBound "True"',
                f'.Xrange "{face}", "{face}"',
                f'.Yrange "{_fmm(-rport)}", "{_fmm(rport)}"',
                f'.Zrange "h_sub-{_fmm(rport)}", "h_sub+{_fmm(rport)}"',
                ".Create", "End With"]))
        _emit_ports = False
    else:
        _emit_ports = True

    # Microstrip waveguide ports on the x faces (standard sizing: ~8W x ~6h).
    # wp is METRES (W, ymax/ymin from Geometry) -- use _f, not _fmm.
    wp = min(8.0 * W, ymax - ymin)
    if _emit_ports:
        s.append("\n' ---- waveguide ports ------------------------------------------\n")
    for n, (xface_e, orient) in enumerate(
            ([(xmin_e, "xmin"), (xmax_e, "xmax")] if _emit_ports else []), start=1):
        s.append(_hist(f"define port{n}", [
            "With Port", ".Reset", f'.PortNumber "{n}"',
            '.NumberOfModes "1"', '.Coordinates "Free"',
            f'.Orientation "{orient}"', '.PortOnBound "True"',
            f'.Xrange "{xface_e}", "{xface_e}"',
            f'.Yrange "{_f(-wp/2)}", "{_f(wp/2)}"',
            '.Zrange "-t_cu", "h_sub*5"',
            ".Create", "End With",
        ]))

    # ---- mesh + solver ----------------------------------------------------
    s.append("\n' ---- mesh + solver setup ------------------------------------------\n")
    s.append(_hist("define mesh settings", [
        "With Mesh", '.MeshType "PBA"',
        '.SetCreator "High Frequency"',
        # Computed directly (2026-09-06, no CST needed): at 25 lines/wl the
        # global cell is ~2.18mm, but the CPWG gap (0.2512mm) needs a cell
        # of ~0.05mm to get even 5 cells across it -- a 43.5x local/global
        # ratio, which the old RatioLimit=20 could never permit no matter
        # how much MeshAdaption wanted to refine there. This is CST's
        # analogue of what Palace does with a small absolute mesh_min: give
        # local refinement generous room rather than just barely clearing
        # the smallest feature. At 35 lines/wl the global cell drops to
        # ~1.56mm, needing only a 31x ratio for that same gap -- RatioLimit
        # 100 clears every feature in this design (CPWG gap, via-via gaps,
        # coax pin) with >3x margin, not a bare pass.
        '.LinesPerWavelength "35"',
        '.MinimumLineNumber "15"',
        '.RatioLimit "100"',
        '.UseRatioLimit "True"',
        "End With",
    ]))
    s.append(_hist("define time domain solver parameters", [
        "Mesh.SetCreator \"High Frequency\"",
        "With Solver",
        '.Method "Hexahedral"',
        '.CalculationType "TD-S"',
        '.StimulationPort "1"', '.StimulationMode "All"',
        # -60dB (not -40) so a sharp Chebyshev null isn't cut off by an
        # early steady-state stop -- deliberate, not the mesh-density bump
        # below that a stray edit briefly introduced and was reverted.
        '.SteadyStateLimit "-60"',
        # NOTE: an earlier revision of this file added .StabilityFactor
        # "0.8" here -- CST 2021 rejected it outright ("No such property or
        # method"), a guessed VBA name that was never actually valid.
        # Removed rather than guessed again. If the instability warning
        # persists, the stability factor has to be set by hand: Home ->
        # Solver -> Setup Solver -> Specials... -> General tab.
        #
        # Real geometric audit (2026-09-06, no CST needed -- computed
        # directly from the same coordinates this macro draws): no
        # overlapping conductors anywhere (worst via-via gap 0.6mm, clean).
        # But at 25 lines/wavelength the global mesh cell is ~2.18mm, while
        # every conductor gap in this design is smaller than that -- the
        # CPWG gap (0.2512mm) is 11% of a cell, via-to-via spacing (0.6mm)
        # is 27%. The whole model leans on CST's automatic local refinement
        # (RatioLimit below) to resolve features 4-9x smaller than the base
        # grid, with no adaptive pass ever checking that refinement actually
        # converged (MeshAdaption was False). Turned on: this is the direct,
        # standard CST mechanism for exactly this situation, not a guess.
        '.MeshAdaption "True"',
        '.StoreTDResultsInCache "False"',
        '.SParaSymmetry "True"',
        "End With",
    ]))

    s.append('''
MsgBox "SIW filter built: " & Solid.GetNumberOfShapes() & " solids. " & _
       "Check the modeler tree, then run the Time Domain solver."

End Sub
''')
    return "".join(s)


def write_bas(path: str | None = None,
              spec: FilterSpec = SPEC,
              geometry: Geometry | None = None,
              launch: dict | None = None,
              sma_len_mm: float = 6.0) -> Geometry:
    """`geometry` overrides the analytical default so a LANDED design can be
    exported (the defaults are not any optimised geometry). `launch` adds the
    real CPWG + Taoglas SMA."""
    if path is None:
        path = out_bas("siw_filter.bas")
    g = geometry if geometry is not None else build_geometry(spec)
    bas = generate_bas(g, launch=launch, sma_len_mm=sma_len_mm)
    with open(path, "w", newline="\r\n") as fh:   # CST/VBA expects CRLF
        fh.write(bas)
    n_lines = bas.count("\n")
    src = "EM-calibrated" if g.iris_calibrated else "PLACEHOLDER"
    # Count the Cylinder blocks actually written, not len(g.vias): that is
    # only the SIW fence and omits the external-iris rows, the launch
    # stitching vias and the SMA stubs, so it read 86 on a macro that emits
    # 122 -- exactly the kind of number that gets quoted as "the via count".
    n_cyl = bas.count("With Cylinder")
    print(f"Wrote {path} ({n_lines} lines, {n_cyl} cylinders "
          f"[{len(g.vias)} fence + {len(g.ext_iris_vias)} external-iris + "
          f"launch/SMA], {src} irises)")
    return g


if __name__ == "__main__":
    write_bas()
    print("Hand siw_filter.bas (+ target.s2p for overlay) to the CST user.")
