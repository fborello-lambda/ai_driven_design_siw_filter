"""Generate a CST Studio Suite 2021 VBA macro (`siw_filter.bas`) building the
SIW bandpass filter as NATIVE parametric 3D solids.

Every scalar dimension is stored with StoreParameter so it can be re-tuned in
the CST GUI; every geometry block is wrapped in AddToHistory so the solids
survive a History rebuild. Via positions are computed here (Python) and
emitted as explicit Cylinder blocks (parametric in radius/height).

Usage by the human with CST 2021:
    CST -> Home -> Macros -> Open VBA Macro Editor -> File > Open siw_filter.bas -> F5
(or Macros > Run on the file). No live link needed.

Run:  uv run python cst_export.py
"""

from __future__ import annotations

from .config import SPEC, FilterSpec, out_bas
from .siw_geometry import Geometry, build_geometry

MM = 1e3  # metres -> mm (CST units set to mm)


def _f(x: float) -> str:
    """Format a length given in METRES as mm for VBA.

    `Geometry` stores metres, so this is the right formatter for anything
    read off `g`. It is the WRONG one for the launch dict, whose fields are
    already millimetres (`cpwg_w_feed_mm`, `sma_rin_mm`, ...) and for
    `gnd_stitch_layout`, which works in mm -- use `_fmm` there. Mixing them
    scales by 1000 without any error: the whole CPWG launch was emitted at
    1000x, with the SMA pin at radius 380mm and the stitching vias 30
    metres off the board, on a macro whose cavity section was correct.
    """
    return f"{x * MM:.4f}"


def _fmm(x: float) -> str:
    """Format a length ALREADY in millimetres for VBA. See `_f`."""
    return f"{x:.4f}"


def _hist(header: str, body_lines: list[str]) -> str:
    """Wrap a VBA command block in AddToHistory (CST history-rebuild safe)."""
    body = '" & vbLf & _\n  "'.join(line.replace('"', '""') for line in body_lines)
    return f'AddToHistory "{header}", "{body}"\n'


def generate_bas(g: Geometry, launch: dict | None = None,
                 sma_len_mm: float = 6.0) -> str:
    """VBA macro for CST. `launch` is a TAOGLAS_CPWG-style dict; when given,
    the feed is built as the REAL launch actually simulated -- coplanar
    ground pours, stitching vias, the narrowed CPWG feed with its taper out
    to the microstrip, and the Taoglas SMA coax stub with coaxial ports --
    instead of a bare constant-width microstrip with waveguide ports."""
    spec, sub = g.spec, g.spec.substrate
    half = g.a_siw / 2.0
    L_inner = g.L_inner
    Lt, Lf, W = g.L_taper, g.L_feed, g.W_ms
    xmin, xmax = -Lt - Lf, L_inner + Lt + Lf          # board ends at the feeds
    _, _, ymin, ymax = g.board
    # Parametric X expressions so W_ms/L_taper/L_feed are LIVE knobs in CST:
    # the board edges and ports track the feed length. L_inner stays numeric
    # (locked to the baked via walls) so changing feed dims never desyncs them.
    Li = _f(L_inner)
    xmin_e = "-(L_taper+L_feed)"
    xmax_e = f"{Li}+L_taper+L_feed"
    t_cu = sub.cu_thickness
    h_air = 6.0 * sub.h                                # air above the board

    s = []
    s.append(f'''\
' =====================================================================
'  SIW bandpass filter — auto-generated by cst_export.py
'  f0 = {spec.f0/1e9:.3f} GHz, N = {spec.N}, FBW = {spec.FBW*100:.1f} %, ripple = {spec.ripple_db} dB
'  substrate: {sub.name} (eps_r = {sub.eps_r}, tan_d = {sub.tan_d}, h = {sub.h*MM:.3f} mm)
'  irises: {"EM-calibrated (openEMS)" if g.iris_calibrated else "ANALYTICAL PLACEHOLDER — run calibrate.py --sweep"}
'  CST Studio Suite 2021 — open in VBA macro editor and press F5.
' =====================================================================
Option Explicit

Sub Main

ResetAll

' ---- units & frequency range -------------------------------------
AddToHistory "define units", "With Units" & vbLf & _
  ".Geometry ""mm""" & vbLf & ".Frequency ""GHz""" & vbLf & _
  ".Time ""ns""" & vbLf & "End With"
AddToHistory "define frequency range", "Solver.FrequencyRange ""2.0"", ""3.6"""
''')

    # ---- parameters ----------------------------------------------------
    params = [
        ("eps_r",  f"{sub.eps_r}",      "substrate Dk"),
        ("tan_d",  f"{sub.tan_d}",      "substrate Df"),
        ("h_sub",  _f(sub.h),           "substrate thickness [mm]"),
        ("t_cu",   _f(t_cu),            "copper thickness [mm]"),
        ("rvia",   _f(spec.d_via / 2),  "via radius [mm]"),
        ("p_via",  _f(spec.p_via),      "via pitch [mm]"),
        ("a_siw",  _f(g.a_siw),         "via-row spacing (SIW width) [mm]"),
        ("L_taper", _f(Lt),             "ms->SIW taper length [mm]"),
        ("L_feed", _f(Lf),              "50-ohm feed length [mm]"),
        ("W_ms",   _f(W),               "50-ohm microstrip width [mm]"),
        ("Lsub",   _f(xmax - xmin),     "board length [mm]"),
        ("Wsub",   _f(ymax - ymin),     "board width [mm]"),
        ("h_air",  _f(h_air),           "air above board [mm]"),
    ]
    # One L_cav per cavity. A single "L_cav" used to be emitted from
    # `g.L_cav`, the SYNTHESIS nominal (34.400mm) -- which on this design is
    # neither of the two cavity lengths actually built (34.239 / 35.503). The
    # solids are placed from baked via coordinates, so the geometry was
    # right and only the GUI label lied; a label that lies about the one
    # dimension a person would tune is still a defect.
    for i, Lc in enumerate(g.L_cavs, start=1):
        params.append((f"L_cav{i}", _f(Lc), f"cavity {i} length [mm] "
                                            f"(read-only: vias are baked)"))
    for i, w in enumerate(g.iris_widths, start=1):
        params.append((f"w_iris{i}{i+1}", _f(w), f"iris {i}-{i+1} width [mm]"))
    # External coupling aperture (input/output iris) -> controls Qe -> bandwidth.
    # Use the geometry's w_ext (Palace-optimized when USE_OPTIMIZED) so the GUI
    # parameter matches the baked via positions.
    params.append(("w_ext", _f(g.w_ext),
                   "EXTERNAL iris gap (input/output) -> Qe -> bandwidth [mm]"))

    s.append("\n' ---- parameters (editable in the GUI) -----------------------------\n")
    for name, val, desc in params:
        s.append(f'StoreParameter "{name}", "{val}"   \' {desc}\n')

    # ---- material -------------------------------------------------------
    mat = sub.name.replace(".", "p")
    s.append("\n' ---- substrate material ------------------------------------------\n")
    s.append(_hist(f"define material: {mat}", [
        "With Material", ".Reset", f'.Name "{mat}"', '.Folder ""',
        '.Type "Normal"', '.Epsilon "eps_r"', '.Mu "1"',
        '.TanD "tan_d"', '.TanDFreq "10"', '.TanDGiven "True"',
        '.TanDModel "ConstTanD"', '.DispModelEps "None"',
        '.Colour "0.75", "0.85", "0.6"', ".Create", "End With",
    ]))

    # ---- substrate + grounds -------------------------------------------
    def brick(name, material, xr, yr, zr):
        return _hist(f"define brick: component1:{name}", [
            "With Brick", ".Reset", f'.Name "{name}"',
            '.Component "component1"', f'.Material "{material}"',
            f'.Xrange "{xr[0]}", "{xr[1]}"',
            f'.Yrange "{yr[0]}", "{yr[1]}"',
            f'.Zrange "{zr[0]}", "{zr[1]}"',
            ".Create", "End With",
        ])

    s.append("\n' ---- substrate + ground planes ------------------------------------\n")
    s.append(brick("substrate", mat,
                   (xmin_e, xmax_e), (_f(ymin), _f(ymax)), ("0", "h_sub")))
    s.append(brick("gnd_bottom", "PEC",
                   (xmin_e, xmax_e), (_f(ymin), _f(ymax)), ("-t_cu", "0")))
    # Top SIW plate covers the cavity section only (tapers/feeds are traces).
    s.append(brick("siw_top", "PEC",
                   ("0", Li), (_f(ymin), _f(ymax)),
                   ("h_sub", "h_sub+t_cu")))

    # ---- vias -----------------------------------------------------------
    s.append("\n' ---- vias (PEC cylinders through the substrate) -------------------\n")
    for i, (x, y) in enumerate(g.vias):
        s.append(_hist(f"define cylinder: component1:via{i:03d}", [
            "With Cylinder", ".Reset", f'.Name "via{i:03d}"',
            '.Component "component1"', '.Material "PEC"',
            '.Axis "z"', '.Outerradius "rvia"', '.Innerradius "0"',
            f'.Xcenter "{_f(x)}"', f'.Ycenter "{_f(y)}"',
            '.Zrange "0", "h_sub+t_cu"', '.Segments "0"',
            ".Create", "End With",
        ]))

    # ---- external coupling irises (input/output) -----------------------
    # Transverse via rows at the SIW input/output faces with a central gap of
    # w_ext. Narrowing w_ext weakens the external coupling (raises Qe), which
    # narrows the bandwidth. The Y positions reference the w_ext parameter so
    # the gap is tunable directly in CST.
    s.append("\n' ---- external coupling irises (gap = w_ext, controls Qe/BW) -------\n")
    # vias per face = total ext iris vias / (2 faces * 2 signs); matches
    # siw_geometry so the .bas never places a via past the side wall.
    n_ext = len(g.ext_iris_vias) // 4
    faces = {"in": "0", "out": _f(L_inner)}
    for fname, xexpr in faces.items():
        for k in range(n_ext):
            off = f"w_ext/2 + {k + 0.5:.1f}*p_via"
            for sgn, tag in (("+", "t"), ("-", "b")):
                yc = f"{off}" if sgn == "+" else f"-({off})"
                s.append(_hist(f"define cylinder: component1:viaext_{fname}_{tag}{k}", [
                    "With Cylinder", ".Reset",
                    f'.Name "viaext_{fname}_{tag}{k}"',
                    '.Component "component1"', '.Material "PEC"',
                    '.Axis "z"', '.Outerradius "rvia"', '.Innerradius "0"',
                    f'.Xcenter "{xexpr}"', f'.Ycenter "{yc}"',
                    '.Zrange "0", "h_sub+t_cu"', '.Segments "0"',
                    ".Create", "End With",
                ]))

    # ---- tapers + feed traces (extruded point-list polygons) -----------
    s.append("\n' ---- microstrip feeds + tapers (extruded copper traces) -----------\n")
    # Coordinates are VBA expressions referencing the feed parameters W_ms,
    # L_taper, L_feed (LIVE in CST). The taper opens to +/-a_siw/2 (numeric,
    # locked to the via walls). hp = half-width string, ht = a_siw/2 numeric.
    hp = "W_ms/2"
    ht = _f(half)
    traces = {
        "taper_in": [("-L_taper", hp), ("0", ht), ("0", f"-({ht})"),
                     ("-L_taper", f"-({hp})")],
        "feed_in": [("-(L_taper+L_feed)", hp), ("-L_taper", hp),
                    ("-L_taper", f"-({hp})"), ("-(L_taper+L_feed)", f"-({hp})")],
        "taper_out": [(f"{Li}+L_taper", hp), (Li, ht), (Li, f"-({ht})"),
                      (f"{Li}+L_taper", f"-({hp})")],
        "feed_out": [(f"{Li}+L_taper+L_feed", hp), (f"{Li}+L_taper", hp),
                     (f"{Li}+L_taper", f"-({hp})"),
                     (f"{Li}+L_taper+L_feed", f"-({hp})")],
    }
    if launch and launch.get("cpwg_gap_mm") is not None:
        # Real CPWG launch: feed narrows to cpwg_w_feed_mm at the board edge
        # and tapers out to the microstrip width where the pours end. The two
        # 50-ohm widths differ (a CPWG's impedance is set by its gap), so a
        # constant-width feed here would NOT be the simulated structure.
        wp = launch["cpwg_w_feed_mm"]; hp2 = _fmm(wp / 2.0)
        clen = launch.get("cpwg_len_mm", 5.0); ctap = launch.get("cpwg_taper_mm", 4.0)
        traces = {
            "feed_in": [(xmin_e, hp2),
                        (f"{xmin_e}+{_fmm(clen)}", hp2),
                        (f"{xmin_e}+{_fmm(clen + ctap)}", hp),
                        ("-L_taper", hp), ("-L_taper", f"-({hp})"),
                        (f"{xmin_e}+{_fmm(clen + ctap)}", f"-({hp})"),
                        (f"{xmin_e}+{_fmm(clen)}", f"-({hp2})"),
                        (xmin_e, f"-({hp2})")],
            "feed_out": [(xmax_e, hp2),
                         (f"{xmax_e}-{_fmm(clen)}", hp2),
                         (f"{xmax_e}-{_fmm(clen + ctap)}", hp),
                         (f"{Li}+L_taper", hp), (f"{Li}+L_taper", f"-({hp})"),
                         (f"{xmax_e}-{_fmm(clen + ctap)}", f"-({hp})"),
                         (f"{xmax_e}-{_fmm(clen)}", f"-({hp2})"),
                         (xmax_e, f"-({hp2})")],
        }
        y_g, y_o = launch["cpwg_y_gnd_mm"], launch["cpwg_y_out_mm"]
        for side, sgn in (("top", 1.0), ("bot", -1.0)):
            for end, xa, xb in (("in", xmin_e, f"{xmin_e}+{_fmm(clen)}"),
                                ("out", f"{xmax_e}-{_fmm(clen)}", xmax_e)):
                traces[f"cpwg_gnd_{end}_{side}"] = [
                    (xa, _fmm(sgn * y_g)), (xb, _fmm(sgn * y_g)),
                    (xb, _fmm(sgn * y_o)), (xa, _fmm(sgn * y_o))]
    for name, pts in traces.items():
        body = ["With Extrude", ".Reset", f'.Name "{name}"',
                '.Component "component1"', '.Material "PEC"',
                '.Mode "pointlist"', '.Height "t_cu"',
                '.Twist "0"', '.Taper "0"',
                '.Origin "0", "0", "h_sub"',
                '.Uvector "1", "0", "0"', '.Vvector "0", "1", "0"',
                f'.Point "{pts[0][0]}", "{pts[0][1]}"']
        for (x, y) in pts[1:]:
            body.append(f'.LineTo "{x}", "{y}"')
        body += [".Create", "End With"]
        s.append(_hist(f"define extrude: component1:{name}", body))

    # ---- CPWG stitching vias + the real Taoglas SMA ---------------------
    if launch and launch.get("cpwg_gap_mm") is not None:
        from .palace_dualmode_driven import gnd_stitch_layout
        # gnd_stitch_layout works in MILLIMETRES; Geometry stores METRES.
        # Passing metres returns an EMPTY via list rather than raising -- the
        # export silently lost all 16 stitching vias until this was caught by
        # grepping the generated .bas for them. Convert explicitly.
        _mm = 1e3
        ym_l = ymax * _mm
        _, gnd_vias = gnd_stitch_layout(
            -(Lt + Lf) * _mm, (L_inner + Lt + Lf) * _mm, W * _mm, ym_l, -ym_l,
            n_gnd_stitch=launch.get("n_gnd_stitch", 6),
            gnd_stitch_offset_mm=launch.get("gnd_stitch_offset_mm", 2.62),
            gnd_stitch_pitch_mm=launch.get("gnd_stitch_pitch_mm", 1.2),
            gnd_via_d_mm=launch.get("gnd_via_d_mm", 0.6),
            gnd_clearance_mm=launch.get("gnd_clearance_mm", 0.3),
            cpwg_gap_mm=launch.get("cpwg_gap_mm"),
            cpwg_y_gnd_mm=launch.get("cpwg_y_gnd_mm"),
            cpwg_y_out_mm=launch.get("cpwg_y_out_mm"),
            cpwg_len_mm=launch.get("cpwg_len_mm", 5.0),
            cpwg_taper_mm=launch.get("cpwg_taper_mm", 4.0))
        rg = launch.get("gnd_via_d_mm", 0.6) / 2.0
        s.append("\n' ---- CPWG ground stitching vias ---------------------------------\n")
        s.append(f"' {len(gnd_vias)} stitching vias (MEASURED from the shared\n"
                 f"' gnd_stitch_layout, the same helper the EM mesh uses)\n")
        for i, (vx, vy) in enumerate(gnd_vias):
            s.append(_hist(f"define cylinder: component1:gndvia{i:03d}", [
                "With Cylinder", ".Reset", f'.Name "gndvia{i:03d}"',
                '.Component "component1"', '.Material "PEC"',
                '.Axis "z"', f'.Outerradius "{_fmm(rg)}"', '.Innerradius "0"',
                f'.Xcenter "{_fmm(vx)}"', f'.Ycenter "{_fmm(vy)}"',
                '.Zrange "-t_cu", "h_sub+t_cu"', '.Segments "0"',
                ".Create", "End With"]))

        # Taoglas EMPCB.SMAFSTJ.B.HT edge launch: a PTFE-filled coax stub off
        # each board edge, pin on the substrate mid-plane. Modelled at the
        # datasheet pin radius; rout follows the 50-ohm PTFE relation.
        rin, rout = launch["sma_rin_mm"], launch["sma_rout_mm"]
        s.append("\n' ---- Taoglas SMA coax stubs (real connector) --------------------\n")
        s.append(_hist("define material: PTFE_sma", [
            "With Material", ".Reset", '.Name "PTFE_sma"', '.Folder ""',
            '.Type "Normal"', f'.Epsilon "{launch["sma_eps_r"]}"', '.Mu "1"',
            f'.TanD "{launch["sma_tand"]}"', '.TanDGiven "True"',
            '.TanDModel "ConstTanD"', '.Colour "0.9", "0.9", "0.9"',
            ".Create", "End With"]))
        for tag, x_edge, sgn in (("in", xmin_e, -1.0), ("out", xmax_e, 1.0)):
            far = f"{x_edge}{'-' if sgn < 0 else '+'}{_fmm(sma_len_mm)}"
            s.append(_hist(f"define cylinder: component1:sma_{tag}_ptfe", [
                "With Cylinder", ".Reset", f'.Name "sma_{tag}_ptfe"',
                '.Component "component1"', '.Material "PTFE_sma"',
                '.Axis "x"', f'.Outerradius "{_fmm(rout)}"',
                f'.Innerradius "{_fmm(rin)}"',
                f'.Xrange "{far}", "{x_edge}"',
                '.Ycenter "0"', '.Zcenter "h_sub/2"', '.Segments "0"',
                ".Create", "End With"]))
            s.append(_hist(f"define cylinder: component1:sma_{tag}_pin", [
                "With Cylinder", ".Reset", f'.Name "sma_{tag}_pin"',
                '.Component "component1"', '.Material "PEC"',
                '.Axis "x"', f'.Outerradius "{_fmm(rin)}"', '.Innerradius "0"',
                f'.Xrange "{far}", "{x_edge}"',
                '.Ycenter "0"', '.Zcenter "h_sub/2"', '.Segments "0"',
                ".Create", "End With"]))

    # ---- boundaries, background, ports ----------------------------------
    s.append("\n' ---- background + boundaries --------------------------------------\n")
    s.append(_hist("define background", [
        "With Background", ".ResetBackground", '.Type "Normal"',
        '.XminSpace "0"', '.XmaxSpace "0"',
        '.YminSpace "0"', '.YmaxSpace "0"',
        '.ZminSpace "0"', '.ZmaxSpace "h_air"',
        "End With",
    ]))
    s.append(_hist("define boundaries", [
        "With Boundary",
        '.Xmin "electric"', '.Xmax "electric"',
        '.Ymin "open"', '.Ymax "open"',
        '.Zmin "electric"', '.Zmax "open"',
        '.ApplyInAllDirections "False"',
        "End With",
    ]))

    if launch and launch.get("cpwg_gap_mm") is not None:
        # COAXIAL ports on the outer face of each SMA stub. The EM model is
        # driven this way (wave ports on the coax cross-section), so
        # microstrip ports here would make the CST run a different problem
        # from the one the design was optimised against.
        rout = launch["sma_rout_mm"]
        s.append("\n' ---- coaxial ports on the SMA stubs -----------------------------\n")
        for n, (x_edge, sgn, orient) in enumerate(
                [(xmin_e, -1.0, "xmin"), (xmax_e, 1.0, "xmax")], start=1):
            face = f"{x_edge}{'-' if sgn < 0 else '+'}{_fmm(sma_len_mm)}"
            s.append(_hist(f"define port{n} (coax)", [
                "With Port", ".Reset", f'.PortNumber "{n}"',
                '.NumberOfModes "1"', '.Coordinates "Free"',
                f'.Orientation "{orient}"', '.PortOnBound "True"',
                f'.Xrange "{face}", "{face}"',
                f'.Yrange "{_fmm(-rout)}", "{_fmm(rout)}"',
                f'.Zrange "h_sub/2-{_fmm(rout)}", "h_sub/2+{_fmm(rout)}"',
                ".Create", "End With"]))
        _emit_ports = False
    else:
        _emit_ports = True

    # Microstrip waveguide ports on the x faces (standard sizing: ~8W x ~6h).
    wp = min(8.0 * W, ymax - ymin)
    if _emit_ports:
        s.append("\n' ---- waveguide ports ------------------------------------------\n")
    for n, (xface_e, orient) in enumerate(
            ([(xmin_e, "xmin"), (xmax_e, "xmax")] if _emit_ports else []), start=1):
        s.append(_hist(f"define port{n}", [
            "With Port", ".Reset", f'.PortNumber "{n}"',
            '.NumberOfModes "1"', '.Coordinates "Free"',
            f'.Orientation "{orient}"', '.PortOnBound "True"',
            f'.Xrange "{xface_e}", "{xface_e}"',
            f'.Yrange "{_fmm(-wp/2)}", "{_fmm(wp/2)}"',
            '.Zrange "-t_cu", "h_sub*5"',
            ".Create", "End With",
        ]))

    # ---- mesh + solver ----------------------------------------------------
    s.append("\n' ---- mesh + solver setup ------------------------------------------\n")
    s.append(_hist("define mesh settings", [
        "With Mesh", '.MeshType "PBA"',
        '.SetCreator "High Frequency"',
        '.LinesPerWavelength "25"',
        '.MinimumLineNumber "10"',
        '.RatioLimit "20"',
        '.UseRatioLimit "True"',
        "End With",
    ]))
    s.append(_hist("define time domain solver parameters", [
        "Mesh.SetCreator \"High Frequency\"",
        "With Solver",
        '.Method "Hexahedral"',
        '.CalculationType "TD-S"',
        '.StimulationPort "1"', '.StimulationMode "All"',
        '.SteadyStateLimit "-40"',
        '.MeshAdaption "False"',
        '.StoreTDResultsInCache "False"',
        '.SParaSymmetry "True"',
        "End With",
    ]))

    s.append('''
MsgBox "SIW filter built: " & Solid.GetNumberOfShapes() & " solids. " & _
       "Check the modeler tree, then run the Time Domain solver."

End Sub
''')
    return "".join(s)


def write_bas(path: str | None = None,
              spec: FilterSpec = SPEC,
              geometry: Geometry | None = None,
              launch: dict | None = None,
              sma_len_mm: float = 6.0) -> Geometry:
    """`geometry` overrides the analytical default so a LANDED design can be
    exported (the defaults are not any optimised geometry). `launch` adds the
    real CPWG + Taoglas SMA."""
    if path is None:
        path = out_bas("siw_filter.bas")
    g = geometry if geometry is not None else build_geometry(spec)
    bas = generate_bas(g, launch=launch, sma_len_mm=sma_len_mm)
    with open(path, "w", newline="\r\n") as fh:   # CST/VBA expects CRLF
        fh.write(bas)
    n_lines = bas.count("\n")
    src = "EM-calibrated" if g.iris_calibrated else "PLACEHOLDER"
    # Count the Cylinder blocks actually written, not len(g.vias): that is
    # only the SIW fence and omits the external-iris rows, the launch
    # stitching vias and the SMA stubs, so it read 86 on a macro that emits
    # 122 -- exactly the kind of number that gets quoted as "the via count".
    n_cyl = bas.count("With Cylinder")
    print(f"Wrote {path} ({n_lines} lines, {n_cyl} cylinders "
          f"[{len(g.vias)} fence + {len(g.ext_iris_vias)} external-iris + "
          f"launch/SMA], {src} irises)")
    return g


if __name__ == "__main__":
    write_bas()
    print("Hand siw_filter.bas (+ target.s2p for overlay) to the CST user.")
